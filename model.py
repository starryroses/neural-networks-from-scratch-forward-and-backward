import numpy as np
def numerical_gradient(f, x, eps=1e-5):
    x = np.array(x)
    gradients = np.zeros_like(x,dtype=float)
    for idx in np.ndindex(x.shape):
        orig = x[idx]
        x[idx] = orig + eps
        f_pos = f(x)
        x[idx] = orig - eps
        f_neg = f(x)
        grad = (f_pos - f_neg)/(2*eps)
        gradients[idx] = grad
        x[idx] = orig
    return gradients

